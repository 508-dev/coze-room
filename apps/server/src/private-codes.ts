// 256^3 = 16,777,216 codes (24 bits). At 100 concurrent users there are about
// nine live rooms, so one random guess has a ~1 in 1.86 million chance of
// finding any room; per-IP join throttling makes repeated guessing impractical.
export function generatePrivateCode(randomIndex: () => number = cryptoRandomIndex): string {
  return [randomIndex(), randomIndex(), randomIndex()]
    .map((index) => {
      const word = PRIVATE_CODE_WORDS[index];
      if (word === undefined) throw new RangeError("private code word index out of range");
      return word;
    })
    .join("-");
}

function cryptoRandomIndex(): number {
  // randomInt stays uniform for any list length, not only powers of two.
  return randomInt(0, PRIVATE_CODE_WORDS.length);
}
